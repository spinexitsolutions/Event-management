// Generates docs/api-reference.md from the Express route files (method, path, auth requirement).
// Usage: node scripts/gen-api-docs.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const MOUNTS = {
  'auth.routes.ts': { authRouter: '/auth' },
  'public.routes.ts': { publicRouter: '/public' },
  'portal.routes.ts': { portalRouter: '/portal' },
  'cms.routes.ts': { pages: '/admin/cms/pages', site: '/admin/cms/site', templates: '/admin/cms/email-templates' },
  'media.routes.ts': { mediaRouter: '/admin/media' },
  'collections.ts': { r: '/admin/content/:collection' },
  'crm.routes.ts': { inquiriesRouter: '/admin/inquiries', clientsRouter: '/admin/clients', staffDirectoryRouter: '/admin/staff-directory' },
  'quotations.routes.ts': { quotationsRouter: '/admin/quotations' },
  'bookings.routes.ts': { bookingsRouter: '/admin/bookings' },
  'finance.routes.ts': { financeRouter: '/admin/finance' },
  'reports.routes.ts': { reportsRouter: '/admin' },
  'settings.routes.ts': { settingsRouter: '/admin/settings' },
  'vendors.routes.ts': { vendorsRouter: '/admin/vendors' },
  'resources.routes.ts': { resourcesRouter: '/admin/resources' },
  'tasks.routes.ts': { tasksRouter: '/admin/tasks' },
  'calendar.routes.ts': { calendarRouter: '/admin/calendar' },
  'guests.routes.ts': { guestsRouter: '/admin/guests', rsvpPublicRouter: '/public' },
  'staff.routes.ts': { staffRouter: '/admin/staff' },
  'notifications.routes.ts': { notificationsRouter: '/notifications', outboxRouter: '/admin/outbox' },
  'webhooks.routes.ts': { webhookRouter: '/webhooks' },
};
const ROUTER_LEVEL = {
  'portal.routes.ts': 'client (own data only)',
  'media.routes.ts': 'media.manage',
  'quotations.routes.ts': 'quotations.manage',
  'collections.ts': 'cms.manage (venues: venues.manage)',
};
const dir = 'server/src/modules';
let out = '# API reference\n\nBase URL: `/api/v1`. Responses are `{ "data": …, "meta"?: … }`; errors are `{ "error": { "code", "message", "details"? } }`.\n';
out += 'Mutating requests require the `X-CSRF-Token` header (value of the `me_csrf` cookie, or `GET /auth/csrf`). Authentication uses the httpOnly `me_session` cookie.\n';
out += 'Request bodies are validated with zod — see the schema next to each route in `server/src/modules/`.\n\n_Generated by `node scripts/gen-api-docs.mjs`._\n';
for (const file of Object.keys(MOUNTS)) {
  const src = readFileSync(`${dir}/${file}`, 'utf8');
  const re = /(\w+)\.(get|post|put|patch|delete)\(\s*\n?\s*'([^']*)'\s*,([^;]*?)(?:ah\(|\(_?req)/g;
  const rows = [];
  let m;
  while ((m = re.exec(src))) {
    const [, router, method, path, mids] = m;
    const prefix = MOUNTS[file][router];
    if (prefix === undefined) continue;
    const perms = [...mids.matchAll(/require(?:Any)?Permission\(([^)]*)\)/g)].map((x) => x[1].replace(/'/g, '').replace(/,\s*/g, ' + '));
    let auth = perms.join(', ');
    if (!auth && /requireAuth/.test(mids)) auth = 'signed in';
    if (!auth && /requireClient/.test(mids)) auth = 'client';
    if (!auth) {
      const use = new RegExp(`${router}\\.use\\((?:require(?:Any)?Permission\\(([^)]*)\\)|(requireClient|requireAuth))`).exec(src);
      auth = use ? (use[1] ? use[1].replace(/'/g, '') : use[2] === 'requireClient' ? 'client' : 'signed in') : ROUTER_LEVEL[file] ?? (prefix.startsWith('/public') || prefix === '/auth' || prefix === '/webhooks' ? 'public' : 'see handler');
    }
    const limits = /formLimiter|authLimiter|paymentLimiter/.exec(mids)?.[0];
    rows.push(`| ${method.toUpperCase()} | \`${(prefix + path).replace(/\/$/, '') || '/'}\` | ${auth}${limits ? ` · rate-limited` : ''} |`);
  }
  if (!rows.length) continue;
  out += `\n## ${file.replace(/\.routes\.ts|\.ts/, '')}\n\n| Method | Path | Access |\n| --- | --- | --- |\n${rows.join('\n')}\n`;
}
writeFileSync('docs/api-reference.md', out);
console.log('docs/api-reference.md written');
