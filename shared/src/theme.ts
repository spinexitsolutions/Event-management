import { z } from 'zod';
import { hexColor, mediaUrl } from './common';

/** Fonts the client can load from Google Fonts. An allowlist prevents arbitrary stylesheet injection. */
export const FONT_OPTIONS = {
  heading: ['Cormorant Garamond', 'Playfair Display', 'Bodoni Moda', 'Cinzel', 'DM Serif Display', 'Italiana', 'Marcellus', 'Fraunces', 'Montserrat', 'Syne'],
  body: ['Inter', 'Manrope', 'Jost', 'Montserrat', 'DM Sans', 'Outfit', 'Lato', 'Karla', 'Nunito Sans'],
} as const;

export const themeTokensSchema = z.object({
  mode: z.enum(['dark', 'light']),
  colors: z.object({
    primary: hexColor,
    secondary: hexColor,
    accent: hexColor,
    background: hexColor,
    surface: hexColor,
    text: hexColor,
    muted: hexColor,
    border: hexColor,
    /** Contrast band colour used by "contrast" section backgrounds and the footer. */
    contrast: hexColor,
    onContrast: hexColor,
    success: hexColor,
    warning: hexColor,
    danger: hexColor,
  }),
  fonts: z.object({ heading: z.enum(FONT_OPTIONS.heading), body: z.enum(FONT_OPTIONS.body) }),
  typography: z.object({
    /** Multiplier for the heading scale (display, h1–h3). */
    headingScale: z.number().min(0.8).max(1.3),
    /** Base body font size in px. */
    bodySize: z.number().int().min(14).max(19),
    headingWeight: z.enum(['300', '400', '500', '600', '700']),
    headingCase: z.enum(['normal', 'uppercase']),
    letterSpacing: z.enum(['tight', 'normal', 'wide']),
  }),
  radius: z.number().int().min(0).max(28),
  buttonShape: z.enum(['pill', 'rounded', 'square']),
  buttonStyle: z.enum(['solid', 'outline', 'underline']),
  cardStyle: z.enum(['flat', 'outline', 'elevated', 'glass']),
  sectionSpacing: z.enum(['compact', 'comfortable', 'spacious']),
  background: z.object({
    pattern: z.enum(['none', 'grain', 'linen', 'deco', 'dots']),
    imageUrl: mediaUrl,
    imageOpacity: z.number().min(0).max(1),
  }),
  header: z.object({
    style: z.enum(['transparent', 'solid', 'centered']),
    sticky: z.boolean(),
    ctaLabel: z.string().trim().max(28),
    ctaHref: z.string().trim().max(200),
    showClientLogin: z.boolean(),
  }),
  footer: z.object({
    style: z.enum(['dark', 'light', 'minimal']),
    showNewsletter: z.boolean(),
  }),
  motion: z.object({
    smoothScroll: z.boolean(),
    intensity: z.enum(['subtle', 'standard', 'cinematic']),
  }),
});
export type ThemeTokens = z.infer<typeof themeTokensSchema>;

